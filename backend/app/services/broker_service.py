"""Common broker surface used by execution, market data and account APIs.

The legacy ``runtime.alpaca`` attribute holds either adapter. Broker responses
use the same normalized order/position fields; broker order IDs remain namespaced.
"""
from typing import Protocol, Any
from app.config import Settings


class BrokerService(Protocol):
    broker_name: str
    paper: bool
    configured: bool
    settings: Settings

    def connection_status(self) -> dict[str, Any]: ...
    def connection_config(self) -> dict[str, Any]: ...
    def get_account(self) -> dict[str, Any]: ...
    def get_positions(self) -> list[dict[str, Any]]: ...
    def get_positions_fresh(self) -> list[dict[str, Any]]: ...
    def get_orders(self, status: str = 'all') -> list[dict[str, Any]]: ...
    def get_open_orders_fresh(self) -> list[dict[str, Any]]: ...
    def get_order_by_client_id(self, client_order_id: str) -> dict[str, Any] | None: ...
    def get_asset(self, symbol: str) -> dict[str, Any]: ...
    def get_clock(self) -> dict[str, Any]: ...
    def get_latest_quotes(self, symbols: list[str]) -> dict[str, Any]: ...
    def get_bars(self, symbols, timeframe, start, end, limit=None, use_cache=False): ...
    def recent_bars(self, symbols, timeframe, bars=300): ...
    def submit_entry_order(self, **kwargs) -> dict[str, Any]: ...
    def submit_exit_order(self, symbol, qty, client_order_id) -> dict[str, Any]: ...
    def submit_trailing_stop(self, **kwargs) -> dict[str, Any]: ...
    def cancel_order(self, order_id): ...
    def cancel_all_orders(self): ...
    def close_all_positions(self): ...
    async def start_streams(self, symbols, bar_callback, trade_callback): ...
    def stop_streams(self) -> None: ...
    def streams_healthy(self) -> bool: ...
